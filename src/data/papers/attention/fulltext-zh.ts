export type PaperSection = {
  id: string
  section: string
  title: string
  paragraphs: string[]
  originalId: string
  source: PaperSource
}

export type FulltextBlock = PaperSection

function block(originalId: string, title: string, ...paragraphs: string[]): PaperSection {
  const source = originalSource(originalId)
  const section = source.section.match(/^\d+(?:\.\d+)*/)?.[0] ?? source.section
  return { id: originalId, section, title, paragraphs, originalId, source }
}

