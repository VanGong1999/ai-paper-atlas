export function filterTimeline(
  events: TimelineEvent[],
  opts: { org?: Org | '全部'; topic?: Topic | '全部'; kind?: Kind | '全部'; q?: string },
) {
  const q = (opts.q || '').trim().toLowerCase()
  return events
    .filter((e) => (opts.org && opts.org !== '全部' ? e.org === opts.org : true))
    .filter((e) => (opts.topic && opts.topic !== '全部' ? e.topics.includes(opts.topic) : true))
    .filter((e) => (opts.kind && opts.kind !== '全部' ? e.kind === opts.kind : true))
    .filter((e) =>
      q
        ? `${e.title} ${e.org} ${e.blurb} ${e.why} ${e.topics.join(' ')}`.toLowerCase().includes(q)
        : true,
    )
    .sort((a, b) => a.date.localeCompare(b.date))
}
