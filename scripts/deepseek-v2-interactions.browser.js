async (page) => {
  const assert=(v,m)=>{if(!v)throw new Error(m)}
  await page.setViewportSize({width:1440,height:900})
  await page.goto('http://127.0.0.1:5184/papers/deepseek-v2?chapter=mla&step=0')
  await page.locator('.v2-reader').waitFor()
  await page.getByLabel('播放速度',{exact:true}).selectOption('2')
  await page.getByRole('button',{name:'播放动画',exact:true}).click()
  await page.waitForFunction(()=>new URL(location.href).searchParams.get('step')==='1')
  await page.getByRole('button',{name:'暂停动画',exact:true}).click()
  await page.waitForTimeout(2700)
  assert(new URL(page.url()).searchParams.get('step')==='1','Pause stops step engine')
  const node=page.locator('.v2-svg-node').filter({hasText:'KV latent'})
  const before=(await node.boundingBox()).width
  await page.getByRole('button',{name:'放大计算图',exact:true}).click()
  await page.getByRole('button',{name:'放大计算图',exact:true}).click()
  assert((await node.boundingBox()).width>before*1.4,'Zoom enlarges graph')
  await page.getByRole('button',{name:'重置计算图缩放',exact:true}).click()
  await page.locator('.v2-svg-node').filter({hasText:'Shared RoPE key'}).click()
  assert((await page.locator('.v2-citation').getAttribute('href')).endsWith('#S2.SS1.SSS3'),'Concept citation follows concept chapter')
  await page.getByRole('button',{name:'关闭概念详解',exact:true}).click()
  const separator=await page.getByRole('separator',{name:'调整目录宽度',exact:true}).boundingBox()
  const old=await page.locator('.v2-sidebar').evaluate(el=>el.clientWidth)
  await page.mouse.move(separator.x+2,separator.y+100)
  await page.mouse.down()
  await page.mouse.move(separator.x+32,separator.y+100,{steps:6})
  await page.mouse.up()
  assert(await page.locator('.v2-sidebar').evaluate(el=>el.clientWidth)>old+20,'Pointer drag resizes sidebar')
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'放大计算图',exact:true}).click()
  const pan=await page.locator('.v2-visual-pan').evaluate(el=>({scroll:el.scrollWidth,width:el.clientWidth}))
  assert(pan.scroll>pan.width,'Mobile zoom permits horizontal scrolling')
  await page.setViewportSize({width:1440,height:900})
  await page.reload()
  await page.locator('.v2-reader').waitFor()
  return {playback:true,pause:true,zoom:true,mobilePan:true,conceptSource:true,pointerResize:true}
}
